// Builds the one file an installed plugin may be: `plugin.js`, with no CSS,
// assets or runtime imports. It borrows Vite from a checkout of block/buzz-app
// (BUZZ_APP, default ../.wt-canvas) so this folder needs no install.
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, process.env.BUZZ_APP ?? "../.wt-canvas");
const require = createRequire(`${app}/package.json`);
const { build } = await import(
  pathToFileURL(require.resolve("vite")).href
);

// Class names get a prefix in place of the app's CSS modules.
const PREFIX = "buzz-canvas-";
const names = new Set();
let css = "";
for (const file of ["panel", "views", "kit"]) {
  const text = await readFile(`${here}/css/${file}.css`, "utf8");
  css += text
    .replace(/^@reference.*$/m, "")
    .replace(/\.(?=[a-zA-Z])([a-zA-Z][\w-]*)/g, (_, name) => {
      names.add(name);
      return `.${PREFIX}${name}`;
    });
}
await writeFile(
  `${here}/src/styles.ts`,
  `// Generated by build.mjs from css/. Do not edit.
export const styles = {
${[...names].sort().map((name) => `  ${name}: "${PREFIX}${name}",`).join("\n")}
} as const;
export const css = ${JSON.stringify(css.replace(/\s+/g, " ").trim())};
`,
);

await build({
  root: here,
  configFile: false,
  envDir: false,
  logLevel: "warn",
  resolve: { alias: { react: `${here}/src/react.ts` } },
  oxc: {
    jsx: { runtime: "classic", pragma: "createElement", pragmaFrag: "Fragment" },
  },
  build: {
    outDir: `${here}/.build`,
    minify: false,
    target: "es2022",
    lib: { entry: `${here}/src/index.tsx`, formats: ["es"], fileName: () => "plugin.js" },
  },
});
const out = await readFile(`${here}/.build/plugin.js`, "utf8");
if (/^\s*import\s/m.test(out) || /\bimport\(/.test(out))
  throw new Error("plugin.js must not import anything at runtime.");
await writeFile(`${here}/plugin.js`, out);
console.log(`plugin.js ${(out.length / 1024).toFixed(1)} kB`);
